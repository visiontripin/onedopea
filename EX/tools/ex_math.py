#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
EX // КАЛЬКУЛЯТОР ПРОПУСКНОЙ СПОСОБНОСТИ
=========================================
Считает физику проекта EX: сколько времени стоит «узнать» N человек,
какие форматы встреч реальны, сколько подписчиков нужно на входе воронки
и сколько стоит один контакт каждого уровня.

Запуск:  python3 EX/tools/ex_math.py
Вывод:   markdown-таблицы, которые вставляются в EX/MATH.md
"""

HOURS_PER_YEAR = 24 * 365.25
WORK_WEEK_H = 40          # предел устойчивой работы «человека-субъекта»
DAYS_PER_YEAR = 365.25

# ─────────────────────────────────────────────────────────────
# УРОВНИ КОНТАКТА (операционализация «узнать человека»)
# ─────────────────────────────────────────────────────────────
LEVELS = [
    # код, описание, минуты на человека, сколько людей можно вести параллельно
    ("L0", "Видел в эфире / в кадре (односторонне)",      0.5,   100000),
    ("L1", "Эфир: имя + голос + 3 факта, 60 сек, 2-way чат", 1.0,  3000),
    ("L2", "Видеозвонок 1:1 или круг, 10 мин, верифицирован", 10.0, 1),
    ("L3", "Очная встреча 45 мин + видеофиксация",         45.0,   1),
    ("L4", "Повторный контакт, знаю жизнь (уровень Данбара)", 600.0, 1),
]

# ─────────────────────────────────────────────────────────────
# ФОРМАТЫ (один «слот» = одна сессия)
# ─────────────────────────────────────────────────────────────
FORMATS = [
    # имя, людей за слот, минут на слот, слотов в день, дней в неделю
    ("1:1 видеозвонок (10 мин)",              1,   10, 32, 5),
    ("Круг 6 человек (40 мин)",               6,   40,  8, 5),
    ("Приём в эфире (90 мин, по 60 сек)",    90,   90,  2, 5),
    ("Эшелон: офлайн-день (8 ч)",           120,  480,  1, 3),
    ("Марафон: 30 дней по 40 встреч",      1200,  480,  1, 30),
]

FUNNEL = [  # воронка «подписчик → зафиксированная встреча»
    ("подписался",                 1.00),
    ("верифицировал личность",     0.60),
    ("дошёл до записи в слот",     0.35),
    ("пришёл / вышел на связь",    0.75),
    ("согласие на публикацию",     0.85),
]


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def fmt_years(hours):
    years = hours / HOURS_PER_YEAR
    if years < 1:
        return f"{years*12:.1f} мес"
    if years < 100:
        return f"{years:.1f} лет"
    return f"{years:.0f} лет"


def section_cost_of_n():
    print("\n### 1. Цена «узнать N человек» в часах\n")
    rows = []
    for n in (100, 1_000, 10_000, 100_000, 1_000_000):
        for code, _, minutes, lanes in LEVELS:
            if code not in ("L2", "L3"):
                continue
            hours = n * minutes / 60 / lanes
            calendar = hours * 168 / WORK_WEEK_H   # календарь при 40 ч/нед
            rows.append([
                f"{n:,}".replace(",", " "),
                code,
                f"{minutes:g} мин",
                f"{hours:,.0f}".replace(",", " "),
                fmt_years(hours),
                fmt_years(calendar),
            ])
    print(table(["N", "уровень", "на человека", "часов контакта",
                 "если 24/7", "если 40 ч/нед"], rows))

    print("\n### 2. Пропускная способность форматов\n")
    rows = []
    for name, people, minutes, per_day, days in FORMATS:
        per_week = people * per_day * days
        years = 1_000_000 / per_week / 52
        rows.append([
            name, people, f"{minutes} мин", per_day, days,
            f"{per_week:,}".replace(",", " "),
            f"{years:.0f} лет" if years >= 1 else f"{years*12:.0f} мес",
        ])
    print(table(["формат", "людей/слот", "длина", "слотов/день", "дней/нед",
                 "людей/нед", "до 1 млн по календарю"], rows))

    print("\n> Колонка «до 1 млн» — календарное время при одном субъекте и полной загрузке.\n"
          "> Отсюда единственный честный вывод: 1 000 000 возможен только как\n"
          "> многоуровневая конструкция L0/L1, а L3 закрывается на ~10 000.\n")


def section_funnel():
    print("\n### 3. Воронка: сколько подписчиков нужно на входе\n")
    mult = 1.0
    rows = []
    for name, rate in FUNNEL:
        mult *= rate
        rows.append([name, f"{rate:.0%}", f"{mult:.3f}"])
    print(table(["шаг", "конверсия", "накопленный выход"], rows))
    print()
    rows = []
    for target in (1_000, 10_000, 100_000, 1_000_000):
        rows.append([f"{target:,}".replace(",", " "),
                     f"{target/mult:,.0f}".replace(",", " ")])
    print(table(["нужно зафиксированных встреч", "нужно подписчиков"], rows))
    print("\n> Прямое следствие: для 1 млн очных встреч нужно ~7,5 млн живых подписчиков.\n"
          "> Значит 1 млн достижим только на L0/L1 — в эфире, а не в комнате.\n")


def section_economics():
    print("\n### 4. Юнит-экономика (EUR, оценка 2026)\n")
    rows = [
        ["L0/L1 — эфир", "0,02–0,15", "камера, свет, звук, модерация чата, стрим-инфра"],
        ["L2 — видеозвонок", "1,0–4,0", "платформа, верификация, ассистент на 10 звонков"],
        ["L3 — очная встреча", "25–60", "нейтральная локация, оператор, дорога, страховка"],
        ["L4 — повторный контакт", "80–200", "время, поездки, ужин, подарок-сувенир"],
    ]
    print(table(["уровень", "EUR / контакт", "что входит"], rows))
    print()
    rows = []
    for n, per in ((1_000, 3), (10_000, 45), (100_000, 3), (1_000_000, 0.12)):
        rows.append([f"{n:,}".replace(",", " "), f"{per:g}", f"{n*per:,.0f}".replace(",", " ")])
    print(table(["контактов", "EUR/контакт (микс)", "прямые расходы, EUR"], rows))


def section_protocol_dose():
    print("\n### 5. Дозировка по слоям Данбара (график замеров)\n")
    layers = [5, 15, 50, 150, 500, 1_500, 10_000, 100_000, 1_000_000]
    rows = []
    for i, n in enumerate(layers):
        gap = "" if i == 0 else f"{n - layers[i-1]:,}".replace(",", " ")
        rituals = {5: "«пятёрка»: кто эти люди и почему именно они",
                   15: "проверка: кого из 15 я не вспомнил за 60 сек",
                   50: "срез: сколько из 50 я знаю по имени",
                   150: "аудит Данбара: кто реально остался",
                   500: "первый «серый слой»: имена без лиц",
                   1_500: "тест на узнавание лиц и имён",
                   10_000: "архивный смотр: сколько я помню из 10 000",
                   100_000: "признание: я их не помню — и это данные",
                   1_000_000: "финал: возврат к пяти"}
        rows.append([f"{n:,}".replace(",", " ") if n >= 10_000 else n, gap,
                     "полная батарея" if n <= 1_500 else "сокращённая батарея",
                     rituals[n]])
    print(table(["веха", "прирост", "замеры", "ритуал"], rows))


if __name__ == "__main__":
    print("# EX // РАСЧЁТЫ (сгенерировано `tools/ex_math.py`)")
    section_cost_of_n()
    section_funnel()
    section_economics()
    section_protocol_dose()
